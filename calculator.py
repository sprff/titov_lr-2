"""Простые арифметические операции: сложение и умножение."""


def add(a, b):
    """Возвращает сумму двух чисел.

    Аргументы:
        a: Первое число.
        b: Второе число.

    Результат:
        Сумма a и b.

    Пример:
        >>> add(2, 3)
        5
    """
    return a + b

def multiply(a, b):
    """Возвращает произведение двух чисел.

    Аргументы:
        a: Первый множитель.
        b: Второй множитель.

    Результат:
        Произведение a и b.

    Пример:
        >>> multiply(2, 3)
        6
    """
    return a * b
